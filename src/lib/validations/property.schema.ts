import { z } from 'zod'

export const propertySchema = z.object({
  title: z.string().min(5, 'Title must be at least 5 characters'),
  slug: z.string().min(3, 'Slug is required'),
  description: z.string().min(20, 'Description must be at least 20 characters'),
  property_type: z.enum(['flat', 'villa', 'plot', 'shop', 'office', 'penthouse', 'other']),
  listing_type: z.enum(['sale', 'rent', 'lease']),
  status: z.enum(['available', 'sold', 'rented', 'under_negotiation', 'hidden']),
  price: z.number().positive('Price must be greater than 0'),
  price_unit: z.enum(['absolute', 'lakh', 'crore']),
  rent_period: z.enum(['monthly', 'yearly']).nullable().optional(),
  bhk: z.number().min(0).max(10).nullable().optional(),
  bathrooms: z.number().min(1).max(10),
  balconies: z.number().min(0).max(10),
  carpet_area: z.number().positive('Carpet area is required'),
  builtup_area: z.number().positive().optional().nullable(),
  area_unit: z.enum(['sqft', 'sqmt']),
  floor_number: z.number().optional().nullable(),
  total_floors: z.number().optional().nullable(),
  furnishing: z.enum(['unfurnished', 'semi_furnished', 'fully_furnished']),
  facing: z.string().optional().nullable(),
  age_of_property: z.string().optional().nullable(),
  possession_date: z.string().optional().nullable(),
  city: z.string().min(2, 'City is required'),
  locality: z.string().min(2, 'Locality is required'),
  society_or_project: z.string().optional().nullable(),
  full_address: z.string().optional().nullable(),
  map_link: z.string().optional().nullable(),
  latitude: z.number().optional().nullable(),
  longitude: z.number().optional().nullable(),
  amenities: z.array(z.string()),
  video_url: z.string().url('Must be a valid URL').optional().or(z.literal('')).nullable(),
  brochure_url: z.string().optional().nullable(),
  floor_plan_url: z.string().optional().nullable(),
  rera_number: z.string().optional().nullable(),
  owner_name: z.string().optional().nullable(),
  owner_phone: z.string().optional().nullable(),
  hide_owner_contact: z.boolean(),
  featured: z.boolean(),
  is_new: z.boolean(),
  is_hot_deal: z.boolean(),
  meta_title: z.string().optional().nullable(),
  meta_description: z.string().optional().nullable(),
  images: z.array(z.object({
    id: z.string().optional(),
    url: z.string().url('Must be a valid image URL'),
    alt_text: z.string().optional().nullable(),
    display_order: z.number(),
    is_cover: z.boolean(),
  })).min(1, 'At least one property image is required'),
})

export type PropertyFormValues = z.infer<typeof propertySchema>
